// Lightweight, dependency-free i18n — client-safe (pure data + a lookup fn) so it
// works in BOTH server components (read the language cookie, call t()) and client
// components (via the LanguageProvider context). A real international crew rarely
// reads English well; a low-English seafarer must be able to run the whole
// seafarer + share flow in his own language, and switch it from anywhere.
//
// Adding a language = add its code to LANGS and fill in the column below. The UI
// falls back to English for any key a language hasn't translated yet, so a partial
// translation is never broken — just partially English.

export type Lang = "en" | "zh" | "ru" | "tl" | "id" | "vi";

export const LANGS: { code: Lang; label: string }[] = [
  { code: "en", label: "English" },
  { code: "zh", label: "中文" },
  { code: "ru", label: "Русский" },
  { code: "tl", label: "Tagalog" },
  // South-East Asian crew languages — Indonesian and Vietnamese seafarers make up
  // a large share of international crews and rarely read maritime English well.
  { code: "id", label: "Bahasa Indonesia" },
  { code: "vi", label: "Tiếng Việt" },
];

export const LANG_COOKIE = "docka_lang";
export const DEFAULT_LANG: Lang = "en";

export function isLang(v: unknown): v is Lang {
  return typeof v === "string" && LANGS.some((l) => l.code === v);
}

